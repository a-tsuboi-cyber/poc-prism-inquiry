const { spawn } = require('child_process');
const fs = require('fs');
const path = require('path');

const PROJECT_ROOT = path.join(__dirname, '..');
const TEST_DIR = path.join(PROJECT_ROOT, 'test');
const REPORTS_DIR = path.join(TEST_DIR, 'reports');

// reportsディレクトリがなければ作成
if (!fs.existsSync(REPORTS_DIR)) {
  fs.mkdirSync(REPORTS_DIR, { recursive: true });
}

console.log('=======================================================');
console.log('🧪 PRISM Automated Unit Test Runner');
console.log('=======================================================');

// テスト実行 (node --test)
const testFiles = [
  'test/common/syntax.test.js',
  'test/common/env.test.js',
  'test/common/datastore.test.js',
  'test/modules/knowledgeService.test.js',
  'test/modules/ticketService.test.js',
  'test/modules/conversationService.test.js',
  'test/modules/geminiService.test.js',
  'test/modules/documentService.test.js',
  'test/modules/teamsService.test.js'
].map(f => path.join(PROJECT_ROOT, f)).filter(f => fs.existsSync(f));

if (testFiles.length === 0) {
  console.error('No test files found in test/');
  process.exit(1);
}

const startTime = Date.now();
const child = spawn(process.execPath, ['--test', ...testFiles], {
  cwd: PROJECT_ROOT,
  stdio: ['pipe', 'pipe', 'pipe'],
  env: { ...process.env, NODE_ENV: 'test' }
});

let stdout = '';
let stderr = '';

child.stdout.on('data', (data) => {
  const str = data.toString();
  stdout += str;
  process.stdout.write(str);
});

child.stderr.on('data', (data) => {
  const str = data.toString();
  stderr += str;
  process.stderr.write(str);
});

child.on('close', (code) => {
  const durationMs = Date.now() - startTime;
  const now = new Date();
  const timestamp = now.toISOString().replace(/[-:T]/g, '').slice(0, 14);
  const formattedDate = `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, '0')}-${String(now.getDate()).padStart(2, '0')} ${String(now.getHours()).padStart(2, '0')}:${String(now.getMinutes()).padStart(2, '0')}:${String(now.getSeconds()).padStart(2, '0')}`;

  const isSuccess = code === 0;
  
  // テスト結果集計
  const passMatches = stdout.match(/✔/g) || [];
  const failMatches = stdout.match(/✖/g) || [];
  const totalPass = passMatches.length;
  const totalFail = failMatches.length;

  const reportFileName = `test-report-${timestamp}.md`;
  const reportPath = path.join(REPORTS_DIR, reportFileName);

  const reportContent = `# 単体テスト実行結果レポート (Unit Test Report)

- **実行日時**: ${formattedDate}
- **実行環境**: Node.js ${process.version} (${process.platform})
- **所要時間**: ${(durationMs / 1000).toFixed(2)}s
- **総合判定**: ${isSuccess ? '✅ **ALL PASS (合格)**' : '❌ **FAIL (不合格)**'}
- **テスト結果サマリー**:
  - 成功 (Pass): **${totalPass}**
  - 失敗 (Fail): **${totalFail}**
  - 終了コード: \`${code}\`

---

## 1. 実行テストファイル一覧

- **プロジェクト非依存 (共通テスト)**:
  - \`test/common/syntax.test.js\`
  - \`test/common/env.test.js\`
  - \`test/common/datastore.test.js\`
- **モジュール固有テスト**:
  - \`test/modules/knowledgeService.test.js\`
  - \`test/modules/ticketService.test.js\`
  - \`test/modules/conversationService.test.js\`
  - \`test/modules/geminiService.test.js\`

---

## 2. 実行ログ詳細 (Standard Output)

\`\`\`text
${stdout.trim()}
\`\`\`

${stderr ? `## 3. エラーログ (Standard Error)\n\n\`\`\`text\n${stderr.trim()}\n\`\`\`\n` : ''}
---
*Generated by Antigravity Auto Tester*
`;

  fs.writeFileSync(reportPath, reportContent, 'utf-8');
  console.log('-------------------------------------------------------');
  console.log(`📄 Test Report Saved: test/reports/${reportFileName}`);
  console.log(`🏁 Result: ${isSuccess ? 'ALL TESTS PASSED ✅' : 'TESTS FAILED ❌'}`);
  console.log('=======================================================');

  process.exit(code);
});
